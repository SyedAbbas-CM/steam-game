#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
LOCAL_DIR="${REPO_ROOT}/docs/workflow/local"

mkdir -p "${LOCAL_DIR}"

cat > "${LOCAL_DIR}/MERMAID_LINK_TEST.local.md" <<EOF
# Mermaid Link Test (Local)

This file is machine-generated by \`tools/workflow/bootstrap_local_workflow.sh\`.

Repo root:

\`${REPO_ROOT}\`

Use this file to verify that your Markdown preview supports Mermaid \`click\` links to local files.

Expected behavior:

1. Open Markdown preview for this file.
2. Render the Mermaid chart.
3. Click each node.
4. Confirm the editor opens the referenced file.

\`\`\`mermaid
flowchart TD
    A["Game Manager"] --> B["Save Data"]
    A --> C["Title Screen"]
    D["Player"] --> E["Dungeon Manager"]

    click A "vscode://file/${REPO_ROOT}/scripts/systems/game_manager.gd"
    click B "vscode://file/${REPO_ROOT}/scripts/systems/save_data.gd"
    click C "vscode://file/${REPO_ROOT}/scripts/ui/title_screen.gd"
    click D "vscode://file/${REPO_ROOT}/scripts/player.gd"
    click E "vscode://file/${REPO_ROOT}/scripts/dungeon/dungeon_manager.gd"
\`\`\`

Fallback plain links:

- [game_manager.gd](${REPO_ROOT}/scripts/systems/game_manager.gd)
- [save_data.gd](${REPO_ROOT}/scripts/systems/save_data.gd)
- [title_screen.gd](${REPO_ROOT}/scripts/ui/title_screen.gd)
- [player.gd](${REPO_ROOT}/scripts/player.gd)
- [dungeon_manager.gd](${REPO_ROOT}/scripts/dungeon/dungeon_manager.gd)
EOF

cat > "${LOCAL_DIR}/LOCAL_ENV.md" <<EOF
# Local Workflow Environment

Generated:

\`$(date)\`

Repo root:

\`${REPO_ROOT}\`

Useful next steps:

1. Open \`${LOCAL_DIR}/MERMAID_LINK_TEST.local.md\`
2. Verify Mermaid click links
3. Start a feature-specific workflow state file from:
   \`${REPO_ROOT}/docs/workflow/WORKFLOW_STATE_TEMPLATE.md\`
EOF

echo "Generated local workflow files in:"
echo "  ${LOCAL_DIR}"
echo
echo "Next:"
echo "  1. Open docs/workflow/local/MERMAID_LINK_TEST.local.md"
echo "  2. Verify Mermaid links in your Markdown preview"
