#!/usr/bin/env python3
"""
Build a single transparent master sprite sheet that contains every item icon
currently in use, leaving empty cells you can paint into when you add new
weapons / armors / consumables.

Layout (16-wide, 32 px tiles):
    Rows  0-15  (cells 0-255)   — mirror of tiles.png  (existing items kept at
                                   their original loy_tile_index value)
    Rows 16-31  (cells 256-511) — mirror of tiles2.png (existing items kept at
                                   their original loy_tile_index value)
    Rows 32-63  (cells 512-1023) — empty / transparent. Free space for new
                                   sprites. Pick any empty cell index and set
                                   that item's loy_tile_index to it.

Output:
    assets/sprites/items_master.png        (512 px × 2048 px, RGBA)
    tools/items_master_index.md            (which cell holds what)

This script DOES NOT yet rewire EquipmentItem to use the master sheet — the
existing item_icon_helper.gd still reads from tiles.png + tiles2.png. To
actually use the master in-game you'd repoint that helper at items_master.png
and adjust the col/row math. Tell me when you're ready and I'll wire it.
"""

import glob
import re
from collections import defaultdict
from PIL import Image

SRC_TILES = 'assets/sprites/loy/tiles.png'
SRC_TILES2 = 'assets/sprites/loy/tiles2.png'

MASTER_PATH = 'assets/sprites/items_master.png'
INDEX_MD = 'tools/items_master_index.md'

TILE_PX = 32
COLS = 16
MIRROR_ROWS = 32      # rows 0-31 mirror the two source sheets
EXTRA_ROWS = 32       # rows 32-63 reserved for new sprites
TOTAL_ROWS = MIRROR_ROWS + EXTRA_ROWS

SLOT_NAMES = {
    0: 'Melee', 1: 'Ranged', 2: 'Magic',
    3: 'Helm', 4: 'Body', 5: 'Shield', 6: 'Boots',
    7: 'Gloves', 8: 'Ring', 9: 'Cloak',
    10: 'Consumable', 11: 'Material', 12: 'Ammo',
}


def scan_items() -> dict[int, list[tuple[str, int, str]]]:
    """idx → list of (item_name, slot_type, path) sharing that tile."""
    out: dict[int, list[tuple[str, int, str]]] = defaultdict(list)
    for p in sorted(glob.glob('resources/items/**/*.tres', recursive=True)):
        with open(p) as f:
            text = f.read()
        name_m = re.search(r'^item_name\s*=\s*"(.+?)"$', text, re.MULTILINE)
        tile_m = re.search(r'^loy_tile_index\s*=\s*(-?\d+)$', text, re.MULTILINE)
        slot_m = re.search(r'^slot_type\s*=\s*(\d+)$', text, re.MULTILINE)
        if not (name_m and tile_m and slot_m):
            continue
        idx = int(tile_m.group(1))
        if idx < 0:
            continue
        out[idx].append((name_m.group(1), int(slot_m.group(1)), p))
    return out


def build_master() -> None:
    tiles = Image.open(SRC_TILES).convert('RGBA')
    tiles2 = Image.open(SRC_TILES2).convert('RGBA')
    assert tiles.size == (512, 512), f"tiles.png expected 512x512, got {tiles.size}"
    assert tiles2.size == (512, 512), f"tiles2.png expected 512x512, got {tiles2.size}"

    master = Image.new('RGBA', (COLS * TILE_PX, TOTAL_ROWS * TILE_PX), (0, 0, 0, 0))

    used = scan_items()

    # Paste every used tile from tiles.png into rows 0-15 of master at the
    # SAME column / row position — preserves loy_tile_index for in-game lookup.
    for idx in range(256):
        if idx not in used:
            continue
        col = idx % COLS
        row = idx // COLS
        src_box = (col * TILE_PX, row * TILE_PX, (col + 1) * TILE_PX, (row + 1) * TILE_PX)
        sprite = tiles.crop(src_box)
        master.paste(sprite, (col * TILE_PX, row * TILE_PX), sprite)

    # Paste tiles2.png tiles into rows 16-31. Master cell index = 256 + idx2;
    # that matches what loy_tile_index >= 256 means in item_icon_helper.gd.
    for idx2 in range(256):
        master_idx = 256 + idx2
        if master_idx not in used:
            continue
        col = idx2 % COLS
        row = idx2 // COLS
        src_box = (col * TILE_PX, row * TILE_PX, (col + 1) * TILE_PX, (row + 1) * TILE_PX)
        sprite = tiles2.crop(src_box)
        master_col = col
        master_row = MIRROR_ROWS // 2 + row  # 16 + row → rows 16-31
        master.paste(sprite, (master_col * TILE_PX, master_row * TILE_PX), sprite)

    master.save(MASTER_PATH)
    print(f"Wrote {MASTER_PATH} ({master.size[0]}×{master.size[1]} px)")

    write_index(used)


def write_index(used: dict[int, list[tuple[str, int, str]]]) -> None:
    """Emit a per-cell map showing which items live at each index."""
    lines: list[str] = []
    lines.append('# Items Master Sheet Index')
    lines.append('')
    lines.append(f'Generated by `tools/build_items_master_sheet.py`. Open '
                 f'`{MASTER_PATH}` in any image editor; the cells listed below '
                 f'are painted, every other cell is transparent and free to use.')
    lines.append('')
    lines.append('## How to read this file')
    lines.append('')
    lines.append('- **Cell #** is the same as the item\'s `loy_tile_index`.')
    lines.append('- Cells **0–255** live in rows 0–15 of the master (mirror of `tiles.png`).')
    lines.append('- Cells **256–511** live in rows 16–31 (mirror of `tiles2.png`).')
    lines.append('- Cells **512–1023** are rows 32–63 — **all empty, all yours**. '
                 'Paint a new sprite into any free cell and set the item\'s '
                 '`loy_tile_index` to that cell number.')
    lines.append('')
    lines.append('To find a sprite by name, ⌘F this file.')
    lines.append('')
    lines.append('## Used cells')
    lines.append('')
    lines.append('| Cell | Row,Col | Items |')
    lines.append('|-----:|:--------|:------|')
    for idx in sorted(used.keys()):
        col = idx % COLS
        row = idx // COLS
        if idx >= 256:
            row = MIRROR_ROWS // 2 + (idx - 256) // COLS
            col = (idx - 256) % COLS
        names = [n for n, _, _ in used[idx]]
        if len(names) > 4:
            names_str = ', '.join(names[:4]) + f', +{len(names) - 4} more'
        else:
            names_str = ', '.join(names)
        lines.append(f'| {idx} | r{row}, c{col} | {names_str} |')
    lines.append('')
    lines.append('## Free cells')
    lines.append('')
    all_used = set(used.keys())
    free_in_existing_range = sorted(set(range(512)) - all_used)
    lines.append(f'- {len(free_in_existing_range)} unused cells in the 0-511 range '
                 f'(mirror of the LoY sheets — some intentional gaps you can fill).')
    lines.append(f'- 512 fully-empty cells in the 512-1023 range (rows 32-63) for new content.')
    lines.append('')
    if free_in_existing_range[:20]:
        lines.append(f'Sample free cells in the 0-511 range: '
                     f'{", ".join(str(i) for i in free_in_existing_range[:20])}…')
    with open(INDEX_MD, 'w') as f:
        f.write('\n'.join(lines))
    print(f"Wrote {INDEX_MD}")


if __name__ == '__main__':
    build_master()
